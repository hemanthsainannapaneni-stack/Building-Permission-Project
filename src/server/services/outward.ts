const parseDay = (v: string | null | undefined, fallback: Date) => {
  if (!v) return fallback;
  const d = new Date(v.length === 10 ? `${v}T12:00:00` : v);
  return Number.isNaN(d.getTime()) ? fallback : d;
};

const AUDIT_ACTION: Record<OutwardAction, string> = {
  MARK_READY: 'OUTWARD_READY',
  DISPATCH: 'OUTWARD_DISPATCHED',
  RECORD_DELIVERY: 'OUTWARD_DELIVERED',
  RECORD_ACKNOWLEDGEMENT: 'OUTWARD_ACKNOWLEDGED',
  RECORD_RETURN: 'OUTWARD_RETURNED',
  CANCEL: 'OUTWARD_CANCELLED',
};

export async function outwardAction(user: AuthUser, id: string, input: OutwardActionInput, meta: Meta) {
  requireView(user);
  requireManage(user);
  const action = input.action as OutwardAction;
  const now = new Date();

  return prisma.$transaction(async (tx) => {
    const row = await tx.outwardEntry.findFirst({
      where: { id, ...scopeWhere(user) },
      select: { id: true, outwardNumber: true, status: true, applicationId: true, sourceType: true, sourceId: true, documentReference: true, dispatchDate: true, deliveredAt: true },
    });
    if (!row) throw notFound('That outward entry could not be found.');
    if (input.expectedStatus && input.expectedStatus !== row.status) {
      throw conflict(`This entry is now ${OUTWARD_STATUS_LABEL[row.status as OutwardStatus] ?? row.status}. Reload to see what changed.`, 'STALE_WRITE');
    }
    if (!canMoveOutward(action, row.status)) {
      throw conflict(`${OUTWARD_ACTION_LABEL[action]} is not possible on an entry that is ${OUTWARD_STATUS_LABEL[row.status as OutwardStatus] ?? row.status}.`);
    }

    const data: Prisma.OutwardEntryUpdateManyMutationInput = { status: OUTWARD_ACTION_RESULT[action] };
    const problems: Array<{ path: string; message: string }> = [];
    const future = (d: Date) => d.getTime() > now.getTime() + 60_000;

    if (action === 'DISPATCH') {
      if (!input.mode) problems.push({ path: 'mode', message: 'Choose how it is being sent.' });
      const when = parseDay(input.dispatchDate, now);
      if (future(when)) problems.push({ path: 'dispatchDate', message: 'The dispatch date cannot be in the future.' });
      if (input.mode && ['REGISTERED_POST', 'SPEED_POST', 'COURIER'].includes(input.mode) && !input.trackingNumber.trim()) {
        problems.push({ path: 'trackingNumber', message: 'Enter the tracking number for a posted or couriered item.' });
      }
      Object.assign(data, { mode: input.mode ?? '', dispatchDate: when, trackingNumber: input.trackingNumber.trim() });
    }
    if (action === 'RECORD_DELIVERY') {
      const when = parseDay(input.deliveredAt, now);
      if (future(when)) problems.push({ path: 'deliveredAt', message: 'The delivery date cannot be in the future.' });
      if (row.dispatchDate && when < new Date(row.dispatchDate.getTime() - 86_400_000)) {
        problems.push({ path: 'deliveredAt', message: 'Delivery cannot be before dispatch.' });
      }
      data.deliveredAt = when;
    }
    if (action === 'RECORD_ACKNOWLEDGEMENT') {
      if (!input.acknowledgement.trim()) problems.push({ path: 'acknowledgement', message: 'Say who acknowledged it, and how.' });
      const when = parseDay(input.acknowledgementDate, now);
      if (future(when)) problems.push({ path: 'acknowledgementDate', message: 'The acknowledgement date cannot be in the future.' });
      Object.assign(data, { acknowledgement: input.acknowledgement.trim(), acknowledgementDate: when });
      if (!row.deliveredAt) data.deliveredAt = when;
    }
    if (action === 'RECORD_RETURN') {
      if (!input.returnReason.trim()) problems.push({ path: 'returnReason', message: 'Say why it came back.' });
      Object.assign(data, { returnReason: input.returnReason.trim(), returnedAt: now });
    }
    if (action === 'CANCEL' && !input.remarks.trim()) problems.push({ path: 'remarks', message: 'Say why it is being cancelled.' });
    if (action === 'CANCEL' && GENERATED_SOURCES.includes(row.sourceType)) {
      problems.push({ path: 'action', message: 'A generated notice or order is not cancelled from Outward; it must be dispatched.' });
    }
    if (problems.length) throw badRequest('Some of the dispatch details are missing or not valid.', problems);
    if (input.remarks.trim()) data.remarks = input.remarks.trim();

    const { count } = await tx.outwardEntry.updateMany({ where: { id: row.id, status: row.status }, data });
    if (!count) throw conflict('Somebody else updated this entry just now. Reload to see what changed.', 'STALE_WRITE');

    const roleKey = user.roleKeys[0] ?? '';
    const to = OUTWARD_ACTION_RESULT[action];
    await tx.outwardEvent.create({
      data: {
        outwardId: row.id,
        action,
        fromStatus: row.status,
        toStatus: to,
        actorId: user.id,
        actorName: user.name,
        actorRoleKey: roleKey,
        remarks: [input.remarks.trim(), action === 'RECORD_RETURN' ? input.returnReason.trim() : '', action === 'RECORD_ACKNOWLEDGEMENT' ? input.acknowledgement.trim() : '']
          .filter(Boolean)
          .join(' — '),
        occurredAt: now,
      },
    });
    await audit(tx, {
      actor: user,
      action: AUDIT_ACTION[action],
      entityType: 'OutwardEntry',
      entityId: row.id,
      applicationId: row.applicationId,
      before: { status: row.status },
      after: {
        status: to,
        outwardNumber: row.outwardNumber,
        mode: data.mode ?? undefined,
        trackingNumber: data.trackingNumber ?? undefined,
        acknowledgement: data.acknowledgement ?? undefined,
      },
      remarks: input.remarks,
      ...meta,
    });

    // Dispatching a notice starts its response window.
    if (action === 'DISPATCH' && row.sourceType === 'ShowCauseNotice') {
      const moved = await tx.showCauseNotice.updateMany({
        where: { id: row.sourceId, status: 'ISSUED' },
        data: { status: 'AWAITING_RESPONSE' },
      });
      if (moved.count) {
        await tx.showCauseEvent.create({
          data: {
            showCauseId: row.sourceId,
            action: 'DISPATCHED',
            fromStatus: 'ISSUED',
            toStatus: 'AWAITING_RESPONSE',
            actorId: user.id,
            actorName: user.name,
            actorRoleKey: roleKey,
            remarks: `Dispatched as ${row.outwardNumber}${input.mode ? ` by ${input.mode.replace(/_/g, ' ').toLowerCase()}` : ''}.`,
            occurredAt: now,
          },
        });
        await audit(tx, {
          actor: user,
          action: 'SHOW_CAUSE_DISPATCHED',
          entityType: 'ShowCauseNotice',
          entityId: row.sourceId,
          applicationId: row.applicationId,
          before: { status: 'ISSUED' },
          after: { status: 'AWAITING_RESPONSE', outwardNumber: row.outwardNumber, noticeNumber: row.documentReference },
          ...meta,
        });
      }
    }

    return { id: row.id, outwardNumber: row.outwardNumber, status: to };
  }, TX_LIMITS);
}

