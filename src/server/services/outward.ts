export async function readOutwardDocument(user: AuthUser, id: string): Promise<string> {
  requireView(user);
  const row = await requireEntry(user, id);
  if (row.sourceType === 'ShowCauseNotice' && row.sourceId) return readShowCauseNotice(user, row.sourceId);
  if (row.sourceType === 'RevocationProceeding' && row.sourceId) return readRevocationOrder(user, row.sourceId);
  return renderOutwardCover({
    outwardNumber: row.outwardNumber,
    documentType: row.documentType,
    documentReference: row.documentReference,
    subject: row.subject,
    applicationNumber: row.application?.applicationNumber ?? '',
    recipient: row.recipient,
    address: row.address,
    assignedDate: row.assignedDate,
    remarks: row.remarks,
  });
}
