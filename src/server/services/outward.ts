export async function createOutward(user: AuthUser, input: CreateOutwardInput, meta: Meta) {
  requireView(user);
  requireManage(user);
  if ((SYSTEM_GENERATED_TYPES as readonly string[]).includes(input.documentType)) {
    throw badRequest('Show cause notices and revocation orders are sent to Outward automatically when they are generated.', [
      { path: 'documentType', message: 'Choose another document type.' },
    ]);
  }

  let app: {
    id: string;
    applicationNumber: string;
    applicant: { name: string | null; ownerName: string; address: string; ownerAddress: string } | null;
    approvalOrder: { orderNumber: string } | null;
  } | null = null;
  const ref = input.application.trim();
  if (ref) {
    app = await prisma.application.findFirst({
      where: {
        deletedAt: null,
        ...applicationScope(user),
        ...(isUuid(ref) ? { id: ref } : { applicationNumber: { equals: ref, mode: 'insensitive' } }),
      },
      select: {
        id: true,
        applicationNumber: true,
        applicant: { select: { name: true, ownerName: true, address: true, ownerAddress: true } },
        approvalOrder: { select: { orderNumber: true } },
      },
    });
    if (!app) throw badRequest('That application could not be found.', [{ path: 'application', message: 'Check the application number.' }]);
  } else if (input.documentType !== 'OTHER') {
    throw badRequest('Name the application this document belongs to.', [{ path: 'application', message: 'Enter the application number.' }]);
  }

  const recipient = input.recipient.trim() || app?.applicant?.ownerName?.trim() || app?.applicant?.name?.trim() || '';
  if (!recipient) throw badRequest('Name the recipient.', [{ path: 'recipient', message: 'Enter who it is addressed to.' }]);
  const address = input.address.trim() || app?.applicant?.ownerAddress?.trim() || app?.applicant?.address?.trim() || '';
  const documentReference =
    input.documentReference.trim() || (input.documentType === 'BPO' ? app?.approvalOrder?.orderNumber ?? '' : '');
  if (input.documentType === 'BPO' && !documentReference) {
    throw badRequest('This application has no building permission order to send.', [
      { path: 'documentReference', message: 'Enter the BPO number.' },
    ]);
  }

  return prisma.$transaction(
    (tx) =>
      createOutwardEntry(
        tx,
        {
          applicationId: app?.id ?? null,
          documentType: input.documentType,
          documentReference,
          sourceType: input.documentType === 'BPO' && app ? 'ApprovalOrder' : '',
          sourceId: '',
          subject: input.subject.trim() || `${documentReference || input.documentType}${app ? ` — ${app.applicationNumber}` : ''}`,
          recipient,
          address,
          status: input.readyForDispatch ? 'READY_FOR_DISPATCH' : 'DRAFT',
          remarks: input.remarks,
        },
        { actor: user, roleKey: user.roleKeys[0] ?? '', now: new Date(), meta }
      ),
    TX_LIMITS
  );
}

