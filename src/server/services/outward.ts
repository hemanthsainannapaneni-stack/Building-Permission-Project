/**
 * THE OUTWARD REGISTER.
 *
 * Clerical: it records that a document left the office, how, and what became
 * of it. It never moves an application. Show cause notices and revocation
 * orders arrive here on their own, created in the transaction that generated
 * them; everything else is entered by hand.
 *
 * One cross-module consequence, and only one: dispatching a show cause notice
 * starts its response window — the notice moves from ISSUED to
 * AWAITING_RESPONSE, because an applicant cannot answer a notice that has not
 * been sent.
 */

type Meta = { ip: string; userAgent: string; correlationId?: string };
const TX_LIMITS = { timeout: 20_000, maxWait: 10_000 } as const;

/** A notice or order generated by its module is dispatched, never cancelled here. */
const GENERATED_SOURCES = ['ShowCauseNotice', 'RevocationProceeding', 'DeveloperRegistration', 'ProfessionalRegistration'];

const APP_SELECT = {
  id: true,
  applicationNumber: true,
  applicant: { select: { name: true, ownerName: true } },
} satisfies Prisma.ApplicationSelect;

function requireView(user: AuthUser) {
  if (!can(user, CAPABILITIES.OUTWARD_VIEW)) throw forbidden('Your role does not include the Outward register.');
}
function requireManage(user: AuthUser) {
  if (!can(user, CAPABILITIES.OUTWARD_MANAGE)) throw forbidden('Your role does not keep the Outward register.');
}

/** Entries for files in scope, plus entries that belong to no file. */
const scopeWhere = (user: AuthUser): Prisma.OutwardEntryWhereInput => ({
  OR: [{ applicationId: null }, { application: { deletedAt: null, ...applicationScope(user) } }],
});

async function requireEntry(user: AuthUser, id: string) {
  if (!isUuid(id)) throw notFound('That outward entry could not be found.');
  const row = await prisma.outwardEntry.findFirst({
    where: { id, ...scopeWhere(user) },
    include: { application: { select: APP_SELECT } },
  });
  if (!row) throw notFound('That outward entry could not be found.');
  return row;
}

const owner = (a: { applicant: { name: string | null; ownerName: string } | null } | null) =>
  a?.applicant?.ownerName?.trim() || a?.applicant?.name?.trim() || '';

/** Links the register can follow back to the document's own record. */
function sourceLink(sourceType: string, sourceId: string): string {
  if (sourceType === 'ShowCauseNotice') return `/show-cause/${sourceId}`;
  if (sourceType === 'RevocationProceeding') return `/revocations/${sourceId}`;
  if (sourceType === 'DeveloperRegistration') return `/developers/${sourceId}`;
  if (sourceType === 'ProfessionalRegistration') return `/professionals/${sourceId}`;
  return '';
}

