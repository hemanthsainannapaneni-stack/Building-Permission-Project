export async function getOutward(user: AuthUser, id: string) {
  requireView(user);
  const row = await requireEntry(user, id);
  const events = await prisma.outwardEvent.findMany({ where: { outwardId: row.id }, orderBy: { occurredAt: 'desc' } });
  const { application, ...rest } = row;
  return {
    ...rest,
    deliveryStatus: deliveryStatusLabel(row.status),
    sourceLink: sourceLink(row.sourceType, row.sourceId),
    application: application ? { id: application.id, applicationNumber: application.applicationNumber, owner: owner(application) } : null,
    events,
    permissions: {
      moves: can(user, CAPABILITIES.OUTWARD_MANAGE)
        ? outwardMoves(row.status).filter((m) => !(m === 'CANCEL' && GENERATED_SOURCES.includes(row.sourceType)))
        : [],
    },
  };
}

