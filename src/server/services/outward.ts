export type OutwardListQuery = {
  q?: string;
  status?: string;
  documentType?: string;
  applicationId?: string;
  page?: number;
  pageSize?: number;
};

export async function listOutward(user: AuthUser, query: OutwardListQuery = {}) {
  requireView(user);
  const and: Prisma.OutwardEntryWhereInput[] = [scopeWhere(user)];
  if (query.status === 'PENDING') and.push({ status: { in: ['DRAFT', 'READY_FOR_DISPATCH'] } });
  else if (query.status && isOutwardStatus(query.status)) and.push({ status: query.status });
  if (query.documentType && isOutwardDocumentType(query.documentType)) and.push({ documentType: query.documentType });
  if (query.applicationId && isUuid(query.applicationId)) and.push({ applicationId: query.applicationId });
  const q = query.q?.trim();
  if (q) {
    and.push({
      OR: [
        { outwardNumber: { contains: q, mode: 'insensitive' } },
        { documentReference: { contains: q, mode: 'insensitive' } },
        { recipient: { contains: q, mode: 'insensitive' } },
        { trackingNumber: { contains: q, mode: 'insensitive' } },
        { application: { applicationNumber: { contains: q, mode: 'insensitive' } } },
      ],
    });
  }
  const where = { AND: and };
  const page = Math.max(1, Math.trunc(query.page ?? 1));
  const pageSize = Math.min(100, Math.max(5, Math.trunc(query.pageSize ?? 20)));
  const [total, rows] = await Promise.all([
    prisma.outwardEntry.count({ where }),
    prisma.outwardEntry.findMany({
      where,
      orderBy: [{ assignedDate: 'desc' }, { outwardNumber: 'desc' }],
      skip: (page - 1) * pageSize,
      take: pageSize,
      include: { application: { select: APP_SELECT } },
    }),
  ]);
  return {
    page,
    pageSize,
    total,
    totalPages: Math.max(1, Math.ceil(total / pageSize)),
    rows: rows.map(({ application, ...r }) => ({
      id: r.id,
      outwardNumber: r.outwardNumber,
      documentType: r.documentType,
      documentReference: r.documentReference,
      recipient: r.recipient,
      address: r.address,
      assignedDate: r.assignedDate,
      dispatchDate: r.dispatchDate,
      mode: r.mode,
      trackingNumber: r.trackingNumber,
      status: r.status,
      deliveryStatus: deliveryStatusLabel(r.status),
      acknowledgement: r.acknowledgement,
      acknowledgementDate: r.acknowledgementDate,
      application: application ? { id: application.id, applicationNumber: application.applicationNumber, owner: owner(application) } : null,
    })),
  };
}

export async function outwardSummary(user: AuthUser) {
  requireView(user);
  const byStatus = await prisma.outwardEntry.groupBy({ by: ['status'], where: scopeWhere(user), _count: { _all: true } });
  const s = Object.fromEntries(byStatus.map((g) => [g.status, g._count._all])) as Record<string, number>;
  const get = (k: OutwardStatus) => s[k] ?? 0;
  return {
    total: Object.values(s).reduce((a, b) => a + b, 0),
    pending: get('DRAFT') + get('READY_FOR_DISPATCH'),
    ready: get('READY_FOR_DISPATCH'),
    inTransit: get('DISPATCHED'),
    delivered: get('DELIVERED') + get('ACKNOWLEDGED'),
    acknowledged: get('ACKNOWLEDGED'),
    returned: get('RETURNED'),
  };
}

